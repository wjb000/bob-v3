#!/usr/bin/env python3
"""Write cad/sim/bob_v3.xml from cad/params.py.

Chassis positions are the printable robot. Arm joint frames are
so101_new_calib.urdf and are not redesigned here. Hub mass is a
placeholder until a wheel is weighed. Not a calibrated simulator.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import params as P  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "cad" / "sim" / "bob_v3.xml"
MANIFEST = ROOT / "cad" / "reports" / "manifest.json"


def m(mm: float) -> str:
    return f"{mm / 1000.0:.4f}".rstrip("0").rstrip(".")


def main() -> None:
    nose = P.DECK_L / 2
    axle_y = P.DECK_W / 2 + 8 + P.WHEEL_WIDTH / 2
    roller_x = P.DECK_L / 2 + P.CASTER_ROLLER_OD / 2 + 8
    px, py = P.plate_center()
    print_kg = 3.2
    if MANIFEST.exists():
        print_kg = json.loads(MANIFEST.read_text())["total_print_mass_g"] / 1000.0
    deck_h = P.DECK_TOP
    tower_h = P.ROD_LEN
    xml = f"""<mujoco model="bob_v3">
  <!-- Generated by cad/write_mjcf.py from cad/params.py. Do not hand-edit.
       Deck {P.DECK_L:.0f} x {P.DECK_W:.0f} mm. Tower centre x = {P.TOWER_X:.0f} mm.
       Arm plate x = {px:.0f} mm, {nose - px:.0f} mm behind the nose.
       Shoulder {P.SHOULDER_LO:.1f} to {P.SHOULDER_HI:.1f} mm. Lift travel {P.TRAVEL:.1f} mm.
       Printed mass {print_kg:.2f} kg is the solid mesh, not a weighed robot.
       Each hub is 1.8 kg until the wheel is weighed. The 36 V motor wiring
       is still unverified and is not in this file. -->
  <compiler angle="radian" autolimits="true"/>
  <option gravity="0 0 -9.81"/>
  <default>
    <joint damping="0.2"/>
    <geom rgba="0.75 0.78 0.72 1" contype="1" conaffinity="1" friction="1 0.05 0.01"/>
  </default>
  <worldbody>
    <body name="base" pos="0 0 0">
      <freejoint name="root"/>
      <geom name="deck" type="box" pos="0 0 {m(deck_h / 2)}" size="{m(P.DECK_L / 2)} {m(P.DECK_W / 2)} {m(deck_h / 2)}" mass="{print_kg:.3f}"/>
      <geom name="tower" type="box" pos="{m(P.TOWER_X)} 0 {m(deck_h + tower_h / 2)}" size="{m(P.TD / 2)} {m(P.TW / 2)} {m(tower_h / 2)}" mass="0.05" rgba="0.6 0.6 0.6 1"/>
      <body name="wheel_left" pos="{m(P.TOWER_X)} {m(axle_y)} {m(P.AXLE_Z)}">
        <joint name="wheel_left" type="hinge" axis="0 1 0" damping="0.05"/>
        <geom name="tire_left" type="cylinder" size="{m(P.WHEEL_OD / 2)} {m(P.WHEEL_WIDTH / 2)}" quat="0.7071068 0.7071068 0 0" mass="1.8" rgba="0.2 0.2 0.2 1"/>
      </body>
      <body name="wheel_right" pos="{m(P.TOWER_X)} {m(-axle_y)} {m(P.AXLE_Z)}">
        <joint name="wheel_right" type="hinge" axis="0 1 0" damping="0.05"/>
        <geom name="tire_right" type="cylinder" size="{m(P.WHEEL_OD / 2)} {m(P.WHEEL_WIDTH / 2)}" quat="0.7071068 0.7071068 0 0" mass="1.8" rgba="0.2 0.2 0.2 1"/>
      </body>
      <body name="roller_nose" pos="{m(roller_x)} 0 {m(P.CASTER_AXLE_Z)}">
        <joint name="roller_nose" type="hinge" axis="0 1 0" damping="0.01"/>
        <geom type="cylinder" size="{m(P.CASTER_ROLLER_OD / 2)} {m(P.CASTER_ROLLER_W / 2)}" quat="0.7071068 0.7071068 0 0" mass="0.02"/>
      </body>
      <body name="roller_tail" pos="{m(-roller_x)} 0 {m(P.CASTER_AXLE_Z)}">
        <joint name="roller_tail" type="hinge" axis="0 1 0" damping="0.01"/>
        <geom type="cylinder" size="{m(P.CASTER_ROLLER_OD / 2)} {m(P.CASTER_ROLLER_W / 2)}" quat="0.7071068 0.7071068 0 0" mass="0.02"/>
      </body>
      <body name="lift" pos="{m(px)} {m(py)} {m(P.PLATE_TOP_LO)}">
        <joint name="lift" type="slide" axis="0 0 1" range="0 {m(P.TRAVEL)}" damping="5"/>
        <geom name="carriage" type="box" pos="-0.05 0 -0.02" size="0.06 0.05 0.03" mass="0.55" rgba="0.3 0.64 1 1"/>
        <body name="base_link">
          <geom name="arm_base" type="box" pos="0 0 0.043" size="0.05 0.035 0.043" mass="0.12" rgba="0.3 0.64 1 1"/>
          <body name="shoulder_link" pos="0.038835 0 0.0624" quat="0 0 1 0">
            <joint name="shoulder_pan" type="hinge" axis="0 0 1" range="-1.92 1.92"/>
            <geom name="shoulder" type="box" size="0.023 0.015 0.02" mass="0.08" rgba="0.88 0.48 0.24 1"/>
            <body name="upper_arm_link" pos="-0.030399 -0.018278 -0.0542" quat="-0.5 0.5 0.5 0.5">
              <joint name="shoulder_lift" type="hinge" axis="0 0 1" range="-1.75 1.75"/>
              <geom name="upper_arm" type="box" pos="-0.05 0 0" size="0.06 0.015 0.015" mass="0.15" rgba="0.3 0.64 1 1"/>
              <body name="lower_arm_link" pos="-0.11257 -0.028 0" quat="0.707105 0 0 0.707108">
                <joint name="elbow_flex" type="hinge" axis="0 0 1" range="-1.75 1.75"/>
                <geom name="lower_arm" type="box" pos="-0.06 0 0" size="0.07 0.015 0.015" mass="0.13" rgba="0.3 0.64 1 1"/>
                <body name="wrist_link" pos="-0.1349 0.0052 0" quat="0.707105 0 0 -0.707108">
                  <joint name="wrist_flex" type="hinge" axis="0 0 1" range="-1.66 1.66"/>
                  <geom name="wrist" type="box" size="0.02 0.015 0.015" mass="0.08" rgba="0.3 0.64 1 1"/>
                  <body name="gripper_link" pos="0 -0.0611 0.0181" quat="0.01721 -0.017208 0.706899 0.706896">
                    <joint name="wrist_roll" type="hinge" axis="0 0 1" range="-2.8 2.8"/>
                    <geom name="wrist_roll" type="box" size="0.02 0.015 0.015" mass="0.07" rgba="0.3 0.64 1 1"/>
                    <body name="jaw" pos="0.0202 0.0188 -0.0234" quat="0.707105 0.707108 0 0">
                      <joint name="gripper" type="hinge" axis="0 0 1" range="-0.17 1.75"/>
                      <geom name="jaw_geom" type="box" pos="0 0 0.016" size="0.018 0.01 0.012" mass="0.04" rgba="0.3 0.64 1 1"/>
                    </body>
                  </body>
                </body>
              </body>
            </body>
          </body>
        </body>
      </body>
    </body>
  </worldbody>
  <actuator>
    <velocity name="drive_left" joint="wheel_left" kv="8"/>
    <velocity name="drive_right" joint="wheel_right" kv="8"/>
    <position name="lift" joint="lift" kp="80" ctrlrange="0 {m(P.TRAVEL)}"/>
    <position name="shoulder_pan" joint="shoulder_pan" kp="20" ctrlrange="-1.92 1.92"/>
    <position name="shoulder_lift" joint="shoulder_lift" kp="20" ctrlrange="-1.75 1.75"/>
    <position name="elbow_flex" joint="elbow_flex" kp="20" ctrlrange="-1.75 1.75"/>
    <position name="wrist_flex" joint="wrist_flex" kp="12" ctrlrange="-1.66 1.66"/>
    <position name="wrist_roll" joint="wrist_roll" kp="8" ctrlrange="-2.8 2.8"/>
    <position name="gripper" joint="gripper" kp="8" ctrlrange="-0.17 1.75"/>
  </actuator>
</mujoco>
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(xml)
    print(f"wrote {OUT} print_kg {print_kg:.3f} past-nose plate {nose - px:.0f} mm behind nose")


if __name__ == "__main__":
    main()
