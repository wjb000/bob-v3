#!/usr/bin/env python3
"""Write BOM.md and PRINT.md from docs/bom.py and cad/reports/manifest.json."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "docs"))
from bom import BOM  # noqa: E402

m = json.loads((ROOT / "cad" / "reports" / "manifest.json").read_text())

lines = ["# Bill of materials", "",
         "November 2026 listings, US dollars, before shipping and tax. Prices move; every line links to a listing to check.",
         "Lines marked **have** are parts Bob v2 already owns. Fastener counts come from the CAD (`cad/reports/manifest.json`) plus about 10%.",
         "Generated by `tools/make_docs.py` from `docs/bom.py`. Edit that file, not this one.", ""]
total = have = 0.0
sec = None
for s, item, qty, each, link, note, owned in BOM:
    if s != sec:
        sec = s
        sub = sum(q * e for ss, _, q, e, *_ in BOM if ss == s)
        lines += ["", f"## {s} (${sub:,.0f})", "", "| Item | Qty | Each | Line | Note |", "| --- | ---: | ---: | ---: | --- |"]
    line = qty * each
    total += line
    have += line if owned else 0
    tag = " **have**" if owned else ""
    lines.append(f"| [{item}]({link}){tag} | {qty} | ${each:,.2f} | ${line:,.2f} | {note} |")
lines += ["", f"**Everything: ${total:,.0f}.** If you already have the Bob v2 hubs, pack, charger and drivers: **${total - have:,.0f}**.", "",
          "## Every screw the CAD drilled", "", "| Qty | Item |", "| ---: | --- |"]
for k, v in m["hardware"].items():
    lines.append(f"| {v} | {k} |")
(ROOT / "BOM.md").write_text("\n".join(lines) + "\n")

names = {"base": "Base", "mast": "Mast and lift", "torso": "Torso", "head": "Head", "arm": "Arms"}
cols = {"shell": "white PETG", "frame": "grey PETG", "dark": "black PETG", "accent": "TPU 95A"}
p = ["# Print list", "",
     f"{m['unique_prints']} unique files, {m['total_prints']} prints, about {m['print_mass_g'] / 1000:.1f} kg of filament at the settings below.",
     f"Every part fits a {m['bed_mm'][0]:.0f} x {m['bed_mm'][1]:.0f} x {m['bed_mm'][2]:.0f} mm volume (Prusa MK4, Ender-3, Bambu A1/P1/X1, Core One).",
     "The STLs in `cad/stl/` are already oriented: flat face down, no rotating. Grams are at 4 walls and 20% gyroid.", "",
     "## Settings", "",
     "- PETG, 0.4 mm nozzle, 0.2 mm layers, 4 walls, 5 top/bottom layers, 20% gyroid unless the table says otherwise.",
     "- Shell tiles (`base_shell_*`, `torso_*`, `head_*`): 3 walls, 15%. They print top-down; the lugs and the lidar slot want a little support.",
     "- Structural parts (`yoke_*`, `carriage`, `clevis_*`, `elbow_*`, `axle_*`, `mast_*`): 5 walls, 30%.",
     "- `pinion_*`: 100% infill. `pad_*`: TPU 95A, 100%.",
     "- Heat-set inserts: M3 x 5.7. Every Ø4.0 hole is an insert. Ø3.4 is clearance, Ø2.6 is thread-forming.",
     "- Supports: the Support column is measured from each oriented STL (faces steeper than 45° not on the bed).",
     "  'none' means under 5 cm². Use tree supports, touching the build plate only where you can.", ""]
for g in ("base", "mast", "torso", "head", "arm"):
    ps = [x for x in m["parts"] if x["group"] == g]
    grams = sum(x["grams"] * x["qty"] for x in ps)
    p += [f"## {names[g]} ({grams / 1000:.2f} kg)", "", "| File | Qty | Colour | Bed mm | g each | Support | Note |", "| --- | ---: | --- | --- | ---: | --- | --- |"]
    for x in ps:
        bed = " x ".join(f"{v:.0f}" for v in x["bed_mm"])
        sup = "none" if x["support_cm2"] < 5 else f"{x['support_cm2']:.0f} cm²"
        p.append(f"| `{x['name']}.stl` | {x['qty']} | {cols.get(x['color'], x['color'])} | {bed} | {x['grams']:.0f} | {sup} | {x['note']} |")
    p.append("")
(ROOT / "PRINT.md").write_text("\n".join(p) + "\n")
print(f"BOM ${total:,.0f} (${total - have:,.0f} to buy), {m['total_prints']} prints")
